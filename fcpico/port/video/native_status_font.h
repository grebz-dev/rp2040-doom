#ifndef NATIVE_STATUS_FONT_H
#define NATIVE_STATUS_FONT_H

#include <stdint.h>

/* Five pixels wide. Bit 4 is the left edge. */
static const uint8_t native_digits[10][7] = {
    {14,17,19,21,25,17,14}, {4,12,4,4,4,4,14},
    {14,17,1,2,4,8,31}, {30,1,1,14,1,1,30},
    {2,6,10,18,31,2,2}, {31,16,30,1,1,17,14},
    {6,8,16,30,17,17,14}, {31,1,2,4,8,8,8},
    {14,17,17,14,17,17,14}, {14,17,17,15,1,2,12},
};
static const uint8_t native_letters[26][7] = {
    {14,17,17,31,17,17,17}, {30,17,17,30,17,17,30},
    {15,16,16,16,16,16,15}, {30,17,17,17,17,17,30},
    {31,16,16,30,16,16,31}, {31,16,16,30,16,16,16},
    {15,16,16,23,17,17,15}, {17,17,17,31,17,17,17},
    {14,4,4,4,4,4,14}, {7,2,2,2,18,18,12},
    {17,18,20,24,20,18,17}, {16,16,16,16,16,16,31},
    {17,27,21,21,17,17,17}, {17,25,21,19,17,17,17},
    {14,17,17,17,17,17,14}, {30,17,17,30,16,16,16},
    {14,17,17,17,21,18,13}, {30,17,17,30,20,18,17},
    {15,16,16,14,1,1,30}, {31,4,4,4,4,4,4},
    {17,17,17,17,17,17,14}, {17,17,17,17,17,10,4},
    {17,17,17,21,21,21,10}, {17,17,10,4,10,17,17},
    {17,17,10,4,4,4,4}, {31,1,2,4,8,16,31},
};

static inline const uint8_t *native_font_rows(char c) {
    if (c >= '0' && c <= '9') return native_digits[c - '0'];
    if (c >= 'A' && c <= 'Z') return native_letters[c - 'A'];
    static const uint8_t percent[7] = {25,25,2,4,8,19,19};
    static const uint8_t slash[7] = {1,1,2,4,8,16,16};
    if (c == '%') return percent;
    if (c == '/') return slash;
    return 0;
}

#endif
