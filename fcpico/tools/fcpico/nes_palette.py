"""nes_palette.py -- the NES/Famicom 2C02 PPU's 64-entry colour table.

The 2C02 does not generate RGB directly: it emits an NTSC composite signal
whose colour depends on the exact analog decoder, so there is no single
"correct" RGB palette -- every emulator and hardware capture publishes a
slightly different table. ``NES_PALETTE_RGB`` below reproduces the palette
commonly published on the NESDev Wiki's "PPU palettes" page
(https://www.nesdev.org/wiki/PPU_palettes, the page's worked "example
palette") and distributed as the built-in default palette of FCEUX and
Nestopia -- it is the table used throughout NES homebrew documentation and
is good enough for the perceptual nearest-colour matching this project needs
(quantising Doom's 8-bit frames onto 13 on-screen NES colours). Swap it for a
measured hardware capture if needed; nothing else in
this file depends on the exact values.

Layout: entry ``$VH`` (``V`` = "value" row 0..3, ``H`` = hue column 0..15) is
``NES_PALETTE_RGB[V * 16 + H]``, matching the PPU palette index. Column 0 of
row 0 is grey (hue "0" has no chroma); ``$0D``/``$0E``/``$0F`` and their
row-1..3 mirrors are the PPU's "blacker than black"/black entries -- do not
pick $0D for anything meant to be displayed (composite blanking territory on
real hardware).
"""

