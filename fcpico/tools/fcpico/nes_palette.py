assert len(NES_PALETTE_RGB) == 64

_PALETTE_ARRAY = np.asarray(NES_PALETTE_RGB, dtype=np.int32)  # (64, 3)

#: The same table as an ``(64, 3)`` ``uint8`` array, for vectorised gather
#: (``NES_PALETTE_RGB_ARRAY[nes_index_array]`` -> RGB array).
NES_PALETTE_RGB_ARRAY = np.asarray(NES_PALETTE_RGB, dtype=np.uint8)


def nearest_nes_color(rgb) -> int:
    """Return the 0..63 NES palette index closest to ``rgb`` in squared RGB distance.

    ``rgb`` is an ``(r, g, b)`` triple (or anything ``numpy`` can broadcast
    against ``(3,)``), each 0..255. Ties break toward the lowest index.
    """
    target = np.asarray(rgb, dtype=np.int32).reshape(3)
    diff = _PALETTE_ARRAY - target
    dist2 = np.einsum("ij,ij->i", diff, diff)
    return int(np.argmin(dist2))
